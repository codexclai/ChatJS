'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, '.project', 'state.json');
const outputPath = path.join(root, 'docs', 'PROJECT_STATE.md');
const state = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

function renderProjectState(data) {
  const rows = [
    ['Project', data.project],
    ['Repository', data.repository],
    ['Node module name', data.moduleName],
    ['Phase', data.phase],
    ['Status', data.status],
    ['Default branch', data.defaultBranch],
    ['Last reviewed', data.lastReviewed],
    ['Runtime policy', data.runtimePolicy]
  ];

  const lines = [
    '# Project State',
    '',
    '> Generated from .project/state.json. Edit the JSON source, then run npm run docs:sync. Do not edit this file directly.',
    '',
    '## Snapshot',
    '',
    '| Field | Current value |',
    '| --- | --- |'
  ];

  for (const row of rows) {
    lines.push('| ' + row[0] + ' | ' + row[1] + ' |');
  }

  lines.push('', '## Completed foundation work', '');
  data.completed.forEach((item, index) => lines.push((index + 1) + '. ' + item));

  lines.push('', '## Not implemented yet', '');
  data.notImplemented.forEach((item) => lines.push('- ' + item));

  lines.push('', '## Immediate next actions', '');
  data.nextActions.forEach((item, index) => lines.push((index + 1) + '. ' + item));

  lines.push('', '## Reference artifact', '');
  lines.push('- Source: ' + data.reference.source);
  lines.push('- Acquisition: ' + data.reference.acquisition);
  lines.push('- Availability: ' + data.reference.availability);
  lines.push('- Evidence limit: ' + data.reference.evidenceLimit);
  lines.push('', '## Continuity rule', '');
  lines.push('The repository is the durable source of truth across chats. Follow docs/CONTINUATION.md and update the state, task queue, decisions, and session log whenever the project changes.');
  lines.push('');
  return lines.join('\n');
}

const expected = renderProjectState(state);
const checkOnly = process.argv.includes('--check');

if (checkOnly) {
  const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (actual !== expected) {
    process.stderr.write('docs/PROJECT_STATE.md is out of date. Run npm run docs:sync and commit the generated change.\n');
    process.exitCode = 1;
  } else {
    process.stdout.write('Generated project state is synchronized.\n');
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected, 'utf8');
  process.stdout.write('Updated docs/PROJECT_STATE.md from .project/state.json.\n');
}
