'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'docs', 'project-state.json');
const outputPath = path.join(root, 'docs', 'PROJECT_STATE.md');
const state = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

function renderProjectState(data) {
  const rows = [
    ['Project', data.project],
    ['Repository', data.repository],
    ['Node module name', data.moduleName],
    ['Phase', data.phase],
    ['Status', data.status],
    ['Default branch', data.defaultBranch],
    ['Last reviewed', data.lastReviewed],
    ['Runtime policy', data.runtimePolicy],
    ['Module archive', data.distributionArchive]
  ];

  const lines = [
    '# Project State',
    '',
    '> Generated from docs/project-state.json. Edit the JSON source, then run npm run docs:sync. Do not edit this file directly.',
    '',
    '## Snapshot',
    '',
    '| Field | Current value |',
    '| --- | --- |'
  ];

  for (const row of rows) lines.push('| ' + row[0] + ' | ' + row[1] + ' |');

  lines.push('', '## Completed work', '');
  data.completed.forEach((item, index) => lines.push((index + 1) + '. ' + item));
  lines.push('', '## Not implemented', '');
  data.notImplemented.forEach((item) => lines.push('- ' + item));
  lines.push('', '## Next actions', '');
  data.nextActions.forEach((item, index) => lines.push((index + 1) + '. ' + item));
  lines.push('', '## Reference artifact', '');
  lines.push('- Source: ' + data.reference.source);
  lines.push('- Acquisition: ' + data.reference.acquisition);
  lines.push('- Availability: ' + data.reference.availability);
  lines.push('- Evidence limit: ' + data.reference.evidenceLimit);
  lines.push('', '## Continuity', '');
  lines.push('Read docs/AI_MEMORY.md and docs/CONTINUATION.md at the start of every new ChatJS work session.');
  lines.push('');

  return lines.join('\n');
}

const expected = renderProjectState(state);
const checkOnly = process.argv.includes('--check');

if (checkOnly) {
  const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';

  if (actual !== expected) {
    let firstDifference = 0;
    const sharedLength = Math.min(actual.length, expected.length);

    while (
      firstDifference < sharedLength &&
      actual.charCodeAt(firstDifference) === expected.charCodeAt(firstDifference)
    ) {
      firstDifference += 1;
    }

    const contextStart = Math.max(0, firstDifference - 40);
    const contextEnd = firstDifference + 80;
    const actualContext = JSON.stringify(actual.slice(contextStart, contextEnd));
    const expectedContext = JSON.stringify(expected.slice(contextStart, contextEnd));

    process.stderr.write(
      'docs/PROJECT_STATE.md is out of date. Run npm run docs:sync and commit the generated change.\\n' +
      'actual_length=' + actual.length + ' expected_length=' + expected.length +
      ' first_difference=' + firstDifference + '\\n' +
      'actual_context=' + actualContext + '\\n' +
      'expected_context=' + expectedContext + '\\n'
    );
    process.exitCode = 1;
  } else {
    process.stdout.write('Generated project state is synchronized.\n');
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected, 'utf8');
  process.stdout.write('Updated docs/PROJECT_STATE.md from docs/project-state.json.\n');
}